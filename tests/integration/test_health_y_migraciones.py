"""/health contra PostgreSQL real y migraciones de Alembic iguales a los modelos ORM."""

import httpx
from alembic import command

from app.main import crear_app
from tests.conftest import configuracion_de_prueba
from tests.integration.conftest import configuracion_alembic


async def test_health_ok_con_la_base_de_datos_disponible(url_base_datos: str) -> None:
    app = crear_app(configuracion_de_prueba(database_url=url_base_datos))
    async with app.router.lifespan_context(app):
        transporte = httpx.ASGITransport(app=app)
        async with httpx.AsyncClient(transport=transporte, base_url="http://pruebas") as cliente:
            r = await cliente.get("/health")
    assert (r.status_code, r.json()["estado"], r.json()["baseDatos"]) == (200, "OK", "OK")


